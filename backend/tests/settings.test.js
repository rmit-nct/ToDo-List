const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { MongoMemoryServer } = require('mongodb-memory-server');
const OTPAuth = require('otpauth');
const User = require('../models/User');
const Session = require('../models/Session');
const Workspace = require('../models/Workspace');
const Task = require('../models/Task');
const { app } = require('../server');
let database, server, base;
before(async () => {
  database = await MongoMemoryServer.create();
  await mongoose.connect(database.getUri('settings-tests'));
  await Promise.all([User.init(), Session.init(), Workspace.init(), Task.init()]);
  server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  base = `http://127.0.0.1:${server.address().port}/api`;
});
after(async () => {
  if (server) await new Promise(resolve => server.close(resolve));
  await mongoose.disconnect();
  await database?.stop();
});
function client() {
  let cookie = '';
  return async (path, method = 'GET', body, expected = 200) => {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', Cookie: cookie }, body: body === undefined ? undefined : JSON.stringify(body) });
    const data = await response.json();
    assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
    const setCookie = response.headers.get('set-cookie');
    if (setCookie) { assert.match(setCookie, /HttpOnly/i); cookie = setCookie.split(';')[0]; }
    return data;
  };
}
test('settings: identity, permissions, password, 2FA, membership and deletion', async () => {
  const owner = client(), member = client(), outsider = client(), anonymous = client();
  const password = 'TestPassword!1234';
  const user = await owner('/auth/register', 'POST', { name: 'Owner', email: 'owner@example.test', password }, 201);
  const teamMember = await member('/auth/register', 'POST', { name: 'Member', email: 'member@example.test', password }, 201);
  await outsider('/auth/register', 'POST', { name: 'Outsider', email: 'outsider@example.test', password }, 201);
  await anonymous('/users/me', 'GET', undefined, 401);
  const workspace = await owner('/workspaces', 'POST', { workspaceName: 'Test team', creatorName: 'Owner' }, 201);
  assert.equal(workspace.ownerId, user.id);
  await member(`/workspaces/${workspace.id}/members`, 'POST', { name: 'Member' }, 201);
  await member(`/workspaces/${workspace.id}/members`, 'POST', { name: 'Member' });
  assert.equal((await owner(`/workspaces/${workspace.id}/members`)).length, 2);
  await outsider(`/workspaces/${workspace.id}/members`, 'GET', undefined, 403);
  await member(`/workspaces/${workspace.id}`, 'PATCH', { name: 'Hijacked' }, 403);
  await anonymous(`/workspaces/${workspace.id}`, 'PATCH', { name: 'Hijacked' }, 403);
  await owner('/users/me', 'PATCH', { name: ' ', title: 'Role' }, 400);
  await owner('/users/me', 'PATCH', { name: 'Updated Owner', title: 'Frontend Developer' });
  assert.equal((await owner(`/workspaces/${workspace.id}`)).members[0].name, 'Updated Owner');
  await owner(`/workspaces/${workspace.id}`, 'PATCH', { name: 'Updated team' });
  assert.equal((await anonymous(`/invites/${workspace.inviteCode}`)).id, workspace.id);
  const task = await owner('/tasks', 'POST', { workspaceId: workspace.id, title: 'Demo', status: 'todo', priority: 'high', dueDate: new Date().toISOString(), assignedMemberId: teamMember.id }, 201);
  await outsider(`/tasks?workspaceId=${workspace.id}`, 'GET', undefined, 403);
  await member(`/tasks/${task.id}`, 'DELETE', {}, 403);
  await member(`/tasks/${task.id}/status`, 'PATCH', { status: 'done' });
  await anonymous('/users/me/tasks', 'GET', undefined, 401);
  assert.deepEqual((await owner('/users/me/tasks')).map(item => item.id), []);
  assert.deepEqual((await member('/users/me/tasks?status=done')).map(item => item.id), [task.id]);
  assert.deepEqual(await outsider('/users/me/tasks'), []);
  await member('/users/me/tasks?status=invalid', 'GET', undefined, 400);
  const otherWorkspace = await member('/workspaces', 'POST', { workspaceName: 'Second team', creatorName: 'Member' }, 201);
  const otherTask = await member('/tasks', 'POST', { workspaceId: otherWorkspace.id, title: 'Other team assignment', status: 'todo', priority: 'low', dueDate: new Date().toISOString(), assignedMemberId: teamMember.id }, 201);
  assert.deepEqual(new Set((await member('/users/me/tasks')).map(item => item.id)), new Set([task.id, otherTask.id]));
  const secondSession = client();
  await secondSession('/auth/login', 'POST', { email: user.email, password });
  await owner('/users/me/password', 'PATCH', { password: 'incorrect', newPassword: 'NewTestPassword!1234' }, 403);
  await owner('/users/me/password', 'PATCH', { password, newPassword: 'NewTestPassword!1234' });
  await secondSession('/users/me', 'GET', undefined, 401);
  await anonymous('/auth/login', 'POST', { email: user.email, password }, 401);
  const setup = await owner('/users/me/2fa/setup', 'POST', { password: 'NewTestPassword!1234' });
  assert.match(setup.qrCode, /^data:image\/png/);
  const otp = new OTPAuth.TOTP({ secret: setup.secret, issuer: 'NEO', label: user.email });
  await owner('/users/me/2fa/enable', 'POST', { code: otp.generate() });
  await anonymous('/auth/login', 'POST', { email: user.email, password: 'NewTestPassword!1234' }, 401);
  await anonymous('/auth/login', 'POST', { email: user.email, password: 'NewTestPassword!1234', code: otp.generate() }, 401);
  // Advance the test fixture's replay counter; no wall-clock sleeps are required.
  await User.updateOne({ id: user.id }, { $set: { lastOtpCounter: -1 } });
  await anonymous('/auth/login', 'POST', { email: user.email, password: 'NewTestPassword!1234', code: otp.generate() });
  await User.updateOne({ id: user.id }, { $set: { lastOtpCounter: -1 } });
  await owner('/users/me/2fa', 'DELETE', { password: 'NewTestPassword!1234', code: otp.generate() });
  await anonymous('/users/me', 'GET', undefined, 401);
  await member(`/workspaces/${workspace.id}`, 'DELETE', { confirmation: 'Updated team', password }, 403);
  await owner(`/workspaces/${workspace.id}/leave`, 'POST', {}, 403);
  await member(`/workspaces/${workspace.id}/leave`, 'POST', {});
  assert.equal((await owner(`/tasks?workspaceId=${workspace.id}`))[0].assignedMemberId, '');
  assert.deepEqual((await member('/users/me/tasks')).map(item => item.id), [otherTask.id]);
  await owner(`/workspaces/${workspace.id}`, 'DELETE', { confirmation: 'wrong', password: 'NewTestPassword!1234' }, 400);
  await owner(`/workspaces/${workspace.id}`, 'DELETE', { confirmation: 'Updated team', password: 'NewTestPassword!1234' });
  assert.equal(await Task.countDocuments({ workspaceId: workspace.id }), 0);
  const finalWorkspace = await owner('/workspaces', 'POST', { workspaceName: 'Delete with account', creatorName: 'Owner' }, 201);
  await owner('/users/me', 'DELETE', { confirmation: 'DELETE', password: 'NewTestPassword!1234' });
  assert.equal(await Workspace.countDocuments({ id: finalWorkspace.id }), 0);
  assert.equal(await User.countDocuments({ id: user.id }), 0);
  await owner('/users/me', 'GET', undefined, 401);
  assert.equal(await User.countDocuments({ id: teamMember.id }), 1);
});
